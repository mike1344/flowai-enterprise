#!/bin/bash
# 双库 + 双账号初始化：每个账号只授予自己数据库的权限（docs/08 §1、ADR-002）
set -euo pipefail

: "${MYSQL_ROOT_PASSWORD:?MYSQL_ROOT_PASSWORD is required}"
: "${FLOWAI_DB_NAME:?FLOWAI_DB_NAME is required}"
: "${FLOWAI_DB_USER:?FLOWAI_DB_USER is required}"
: "${FLOWAI_DB_PASSWORD:?FLOWAI_DB_PASSWORD is required}"
: "${INDUSTRIAL_DB_NAME:?INDUSTRIAL_DB_NAME is required}"
: "${INDUSTRIAL_DB_USER:?INDUSTRIAL_DB_USER is required}"
: "${INDUSTRIAL_DB_PASSWORD:?INDUSTRIAL_DB_PASSWORD is required}"

# MySQL 8 新建账号默认无任何权限；只显式授予本库 USAGE 之外的库级权限。
mysql --protocol=socket -uroot -p"${MYSQL_ROOT_PASSWORD}" <<EOSQL
CREATE DATABASE IF NOT EXISTS \`${FLOWAI_DB_NAME}\`
  CHARACTER SET utf8mb4 COLLATE utf8mb4_0900_ai_ci;
CREATE DATABASE IF NOT EXISTS \`${INDUSTRIAL_DB_NAME}\`
  CHARACTER SET utf8mb4 COLLATE utf8mb4_0900_ai_ci;

CREATE USER IF NOT EXISTS '${FLOWAI_DB_USER}'@'%' IDENTIFIED BY '${FLOWAI_DB_PASSWORD}';
CREATE USER IF NOT EXISTS '${INDUSTRIAL_DB_USER}'@'%' IDENTIFIED BY '${INDUSTRIAL_DB_PASSWORD}';

-- 仅本库权限，且不授予全局权限，保证两库互不可见
GRANT ALL PRIVILEGES ON \`${FLOWAI_DB_NAME}\`.* TO '${FLOWAI_DB_USER}'@'%';
GRANT ALL PRIVILEGES ON \`${INDUSTRIAL_DB_NAME}\`.* TO '${INDUSTRIAL_DB_USER}'@'%';

FLUSH PRIVILEGES;
EOSQL

echo "[init] databases and scoped accounts ready: ${FLOWAI_DB_NAME} / ${INDUSTRIAL_DB_NAME}"